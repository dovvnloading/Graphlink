import { useEffect, useState } from "react";
import type { WsTransport } from "../../lib/ws/transport";
import { TOPIC_VALIDATORS } from "../../lib/api-contract/topics";
import type { AppSettingsState } from "../../lib/bridge-core/generated/app-settings-state";
import { Dialog } from "../overlays/overlays";

/**
 * The settings dialog (Qt-removal plan R2.5d, extended R7.4a) - settings
 * island's SPA successor. General + Integrations + API-provider pages are
 * real. Ollama/Llama.cpp remain deferred (R7.4b/R7.4c) - both need a native
 * file-picker capability that doesn't exist yet in graphlink_desktop.py -
 * rendered here as disabled placeholders with an explicit label rather than
 * faking them, the same explicit-defer discipline as the app bar's disabled
 * Save/provider-select.
 */

const SECTIONS = ["General", "Ollama (Local)", "Llama.cpp (Local)", "API Endpoint", "Integrations"] as const;
type Section = (typeof SECTIONS)[number];

const DEFERRED_SECTIONS = new Set<Section>(["Ollama (Local)", "Llama.cpp (Local)"]);

const THEME_OPTIONS = [
  { value: "dark", label: "Dark" },
  { value: "muted", label: "Muted" },
  { value: "mono", label: "Monochromatic" },
];

const NOTIFICATION_TYPE_LABELS: Record<string, string> = {
  info: "Info",
  success: "Success",
  warning: "Warning",
  error: "Error",
};

// Mirrors graphlink_task_config.py's API_PROVIDER_* constants exactly (the
// wire values backend/settings.py's SettingsManager persists) - not an enum
// generated by codegen since these 3 strings are the whole of a small,
// stable, hand-maintained set, the same convention SECTIONS above follows.
const API_PROVIDER_OPENAI = "OpenAI-Compatible";
const API_PROVIDER_ANTHROPIC = "Anthropic Claude";
const API_PROVIDER_GEMINI = "Google Gemini";
const API_PROVIDERS = [API_PROVIDER_OPENAI, API_PROVIDER_ANTHROPIC, API_PROVIDER_GEMINI] as const;
// Mirrors SettingsManager.get_api_base_url()'s own default (graphlink_licensing.py).
const DEFAULT_OPENAI_BASE_URL = "https://api.openai.com/v1";

// Mirrors graphlink_task_config.py's TASK_* constants exactly.
const TASK_TITLE = "task_title";
const TASK_CHAT = "task_chat";
const TASK_CHART = "task_chart";
const TASK_IMAGE_GEN = "task_image_gen";
const TASK_WEB_VALIDATE = "task_web_validate";
const TASK_WEB_SUMMARIZE = "task_web_summarize";

const API_TASK_FIELDS: { task: string; label: string }[] = [
  { task: TASK_TITLE, label: "Chat Naming / Session Title" },
  { task: TASK_CHAT, label: "Chat, Explain, Takeaways (main model)" },
  { task: TASK_CHART, label: "Chart Generation (code-capable model)" },
  { task: TASK_IMAGE_GEN, label: "Image Generation" },
  { task: TASK_WEB_VALIDATE, label: "Web Content Validation" },
  { task: TASK_WEB_SUMMARIZE, label: "Web Content Summarization" },
];

const initialState: AppSettingsState = {
  schemaVersion: 1,
  minCompatibleSchemaVersion: 1,
  revision: 0,
  activeSection: "General",
  theme: "dark",
  showTokenCounter: true,
  enableSystemPrompt: true,
  notificationPreferences: {},
  githubTokenConfigured: false,
  activeApiProvider: API_PROVIDER_OPENAI,
  viewingApiProvider: API_PROVIDER_OPENAI,
  apiBaseUrl: DEFAULT_OPENAI_BASE_URL,
  apiKeyConfigured: { openai: false, anthropic: false, gemini: false },
  apiModels: {},
  apiModelCatalog: [],
  apiCatalogStatus: "idle",
  apiCatalogMessage: "Model catalog has not been refreshed yet.",
  geminiStaticModels: [],
  geminiStaticImageModels: [],
};

function sectionKey(section: Section): string {
  // Backend storage is UI-navigation-only for this field (mirrors the
  // legacy bridge - see backend/settings.py's active_section cell), so any
  // stable string works; reusing the display name keeps the wire traffic
  // human-readable in the WS inspector.
  return section === "General" ? "general" : section === "Integrations" ? "integrations" : section.toLowerCase();
}

function GeneralPage({
  state,
  transport,
}: {
  state: AppSettingsState;
  transport: WsTransport;
}) {
  return (
    <div className="settings-general-page">
      <label className="settings-field">
        <span className="settings-field-label">Theme</span>
        <select
          className="settings-select"
          value={state.theme}
          onChange={(event) => transport.intent("app-settings", "setTheme", [event.target.value])}
        >
          {THEME_OPTIONS.map(({ value, label }) => (
            <option key={value} value={value}>
              {label}
            </option>
          ))}
        </select>
      </label>

      <label className="settings-checkbox-row">
        <input
          type="checkbox"
          checked={state.showTokenCounter}
          onChange={(event) => transport.intent("app-settings", "setShowTokenCounter", [event.target.checked])}
        />
        Show Token Counter Overlay
      </label>

      <label className="settings-checkbox-row">
        <input
          type="checkbox"
          checked={state.enableSystemPrompt}
          onChange={(event) => transport.intent("app-settings", "setEnableSystemPrompt", [event.target.checked])}
        />
        Enable Assistant System Prompt
      </label>

      <fieldset className="settings-fieldset">
        <legend>Notification types</legend>
        {Object.keys(NOTIFICATION_TYPE_LABELS).map((type) => (
          <label className="settings-checkbox-row" key={type}>
            <input
              type="checkbox"
              checked={state.notificationPreferences[type] ?? true}
              onChange={(event) =>
                transport.intent("app-settings", "setNotificationPreference", [type, event.target.checked])
              }
            />
            {NOTIFICATION_TYPE_LABELS[type]}
          </label>
        ))}
      </fieldset>
    </div>
  );
}

